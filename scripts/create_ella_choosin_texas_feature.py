def fresh_read():
    return runner.http(runner.DESK_API + "?nocache=" + str(time.time_ns()), runner.desk_key())

def ensure_body_photo():
    try:
        req = urllib.request.Request(BODY_PHOTO_URL + "?check=" + str(time.time_ns()),
                                     headers={"User-Agent": runner.UA})
        with urllib.request.urlopen(req, timeout=45) as r:
            blob = r.read(32)
            if r.status == 200 and blob:
                print("BODY_PHOTO already staged")
                return
    except Exception:
        pass

    req = urllib.request.Request(BODY_PHOTO_SOURCE, headers={"User-Agent": runner.UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        raw = r.read()
        ctype = (r.headers.get("Content-Type") or "image/webp").split(";", 1)[0].lower()
    if ctype not in {"image/jpeg", "image/png", "image/webp"}:
        raise RuntimeError("unexpected body photo type: " + ctype)
    if len(raw) > 3_000_000:
        raise RuntimeError("body photo exceeds upload limit")
    data = "data:" + ctype + ";base64," + base64.b64encode(raw).decode("ascii")
    uploaded = runner.http("https://music98.news/api/photo", runner.desk_key(),
                           {"name": BODY_PHOTO_NAME, "data": data}, method="POST")
    if not uploaded.get("ok"):
        raise RuntimeError("body photo upload failed: " + json.dumps(uploaded))
    print("BODY_PHOTO staged", uploaded.get("bytes"))

def media_layout(body):
    return [(i, p) for i, p in enumerate(gate.paragraphs(body)) if gate.is_media(p)]

